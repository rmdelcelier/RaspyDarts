import os
import re
import stat
import time
import zlib
import shutil
import filecmp
import tarfile
import json
import hashlib
import requests

from threading import Thread
from datetime import datetime

from include import cpaths

RASPYDARTS_HOME = cpaths.ROOT_DIR
BACKUP_PATH = f'{RASPYDARTS_HOME}/backup'
VERSION_FILE = f'{RASPYDARTS_HOME}/VERSION'
# Folder of the game inside light updates and backups : the installation folder, or
# pydarts/ in the updates published for the installations made before the renaming
ARCHIVE_ROOTS = (RASPYDARTS_HOME.strip('/').split('/'), ['pydarts'])
GITHUB_REPO = 'rmdelcelier/RaspyDarts'
RELEASES_URL = f'https://api.github.com/repos/{GITHUB_REPO}/releases?per_page=100'
ARCHIVE_URL = f'https://github.com/{GITHUB_REPO}/archive/refs/tags'
HEADERS = {"User-Agent": "RaspyDarts"}
TIMEOUT = (10, 30)
# V4.6.1_202610131831 (VERSION file)
VERSION_PATTERN = re.compile(r'[vV](\d+)\.(\d+)\.(\d+)')
# Releases for Raspberry Pi OS Trixie (4.6.1 and later) : _v4.6.1. The installations under
# Buster (4.5.2 and before) only look at the releases named v4.5.2 : they never install a
# version which needs another system
TAG_PATTERN = re.compile(r'^_v(\d+)\.(\d+)\.(\d+)$')
# Light update generated by MakeUpdate.sh and attached to the GitHub release
UPDATE_PATTERN = re.compile(r'^update_V(\d+)\.(\d+)\.(\d+)_\d{8}_\d{4}\.tgz$')

def get_version(logs):
    """
    Return actual version of raspydarts stored in VERSION file
    """

    with open (VERSION_FILE, 'r', encoding="utf-8") as version_file:
        data = version_file.readlines()

    logs.info(f"Version of raspydarts is {data[0].strip()}")

    return data[0].strip()

def set_version(logs, version):
    """
    Update VERSION file with version
    """

    with open(VERSION_FILE, 'w', encoding="utf-8") as version_file:
        version_file.write(f'{version}')
    version_file.close()
    logs.debug(f"Version set : {version}")

def parse_version(version):
    """
    Return (major, minor, patch) of a version or a tag, None if not readable
    """

    match = VERSION_PATTERN.match(version.strip())
    if match is None:
        return None

    return tuple(int(number) for number in match.groups())

def parse_tag(tag):
    """
    Return (major, minor, patch) of the name of a release for this system, None otherwise
    """

    match = TAG_PATTERN.match(tag.strip())
    if match is None:
        return None

    return tuple(int(number) for number in match.groups())

def get_last(logs, actual_version):
    """
    Look for a GitHub release newer than actual_version
    Return None if up to date (or error), else a dict describing the file to download :
        the light update attached to the release if only one version behind,
        else the full source archive of the release
    """

    current = parse_version(actual_version) or (0, 0, 0)

    try:
        res = requests.get(RELEASES_URL, timeout=TIMEOUT, \
                headers=dict(HEADERS, Accept="application/vnd.github+json"))
        res.raise_for_status()
        releases = res.json()
    except (requests.exceptions.RequestException, ValueError) as exc:
        logs.error(f"Unable to reach {RELEASES_URL} ({exc})")
        return None

    newer = []
    for release in releases:
        if release.get('draft') or release.get('prerelease'):
            continue
        number = parse_tag(release.get('tag_name') or '')
        if number is not None and number > current:
            newer.append((number, release))

    if len(newer) == 0:
        logs.debug("NO availables update")
        return None

    newer.sort(key=lambda item: item[0])
    number, release = newer[-1]
    version = 'V{}.{}.{}'.format(*number)

    asset = None
    for candidate in release.get('assets', []):
        match = UPDATE_PATTERN.match(candidate['name'])
        if match and tuple(int(value) for value in match.groups()) == number:
            asset = candidate

    if asset is None or len(newer) > 1:
        # No light update, or more than one version behind : full source archive
        update = {'version': version, 'full': True, 'file': f'github_{version}.tgz', \
                'url': f"{ARCHIVE_URL}/{release['tag_name']}.tar.gz", 'size': None}
    else:
        update = {'version': version, 'full': False, 'file': asset['name'], \
                'url': asset['browser_download_url'], 'size': asset['size']}

    logs.info(f"Update available : {update}")

    return update

def archive_members(archive, full):
    """
    Yield (member, path relative to the game folder) for each file and folder of an archive
    Full source archive : files are in a root folder (RaspyDarts-x.y.z/)
    Light update or backup : files are in the game folder (see ARCHIVE_ROOTS)
    """

    for member in archive:
        parts = [part for part in member.name.split('/') if part not in ('', '.')]
        if '..' in parts:
            raise ValueError(f"Unexpected path in archive : {member.name}")
        if full:
            parts = parts[1:]
        else:
            for root in ARCHIVE_ROOTS:
                if parts[:len(root)] == root:
                    parts = parts[len(root):]
                    break
            else:
                # Parent folders of the game folder are listed too in a backup
                if any(root[:len(parts)] == parts for root in ARCHIVE_ROOTS):
                    continue
                raise ValueError(f"Unexpected path in archive : {member.name}")
        if len(parts) == 0 or parts[0].startswith('.git'):
            continue
        if member.isfile() or member.isdir():
            yield member, '/'.join(parts)

def download_update(logs, update):
    """
    Download an update returned by get_last in backup folder and check it
    """

    file_name = f"{BACKUP_PATH}/{update['file']}"
    partial = f"{file_name}.part"

    try:
        with requests.get(update['url'], headers=HEADERS, stream=True, timeout=TIMEOUT) as res:
            res.raise_for_status()
            with open(partial, 'wb') as downloaded:
                for chunk in res.iter_content(chunk_size=1024 * 1024):
                    downloaded.write(chunk)

        file_size = os.path.getsize(partial)
        if update['size'] is not None and file_size != update['size']:
            raise ValueError(f"size differs from announced ({file_size} vs {update['size']})")

        # Read the whole archive : detects truncated or corrupted files
        with tarfile.open(partial, 'r:gz') as archive:
            files = [relative for member, relative in archive_members(archive, update['full'])]
        if 'VERSION' not in files:
            raise ValueError("VERSION file is missing")

        os.replace(partial, file_name)

    except (requests.exceptions.RequestException, tarfile.TarError, zlib.error, \
            EOFError, OSError, ValueError) as exc:
        logs.error(f"Download of {update['url']} failed ({exc})")
        if os.path.isfile(partial):
            os.remove(partial)
        return False

    logs.debug(f"{update['file']} correctly downloaded ({file_size} bytes)")
    return True

def install_archive(file_name, full, rollback=None):
    """
    Copy files of an archive in the game folder. Identical files are left untouched
    Replaced files are first saved in rollback archive, if given
    Return number of written files
    """

    count = 0

    with tarfile.open(file_name, 'r:gz') as archive:
        for member, relative in archive_members(archive, full):
            target = os.path.join(RASPYDARTS_HOME, relative)
            if member.isdir():
                os.makedirs(target, exist_ok=True)
                continue

            os.makedirs(os.path.dirname(target), exist_ok=True)
            temporary = f"{target}.new"
            try:
                with archive.extractfile(member) as source, open(temporary, 'wb') as new_file:
                    shutil.copyfileobj(source, new_file)

                if os.path.isfile(target):
                    if filecmp.cmp(temporary, target, shallow=False):
                        continue
                    if rollback is not None:
                        rollback.add(target, arcname=f"{RASPYDARTS_HOME.strip('/')}/{relative}")
                    # Keep rights and owner of the replaced file
                    reference = os.stat(target)
                    mode = stat.S_IMODE(reference.st_mode)
                else:
                    reference = os.stat(os.path.dirname(target))
                    mode = (member.mode & 0o777) or 0o644
                    if target.endswith('.sh'):
                        mode |= 0o111

                os.chmod(temporary, mode)
                try:
                    os.chown(temporary, reference.st_uid, reference.st_gid)
                except OSError:
                    pass
                os.replace(temporary, target)
                count += 1
            finally:
                if os.path.isfile(temporary):
                    os.remove(temporary)

    return count

def apply_update(logs, update):
    """
    Apply an update downloaded by download_update
    Replaced files are saved in backup folder, in update_<previous version>_<date>.tgz
    (restorable with Backup.sh r <file>), and restored if update fails
    Return new version, None if update failed
    """

    file_name = f"{BACKUP_PATH}/{update['file']}"
    previous = 'V{}.{}.{}'.format(*(parse_version(get_version(logs)) or (0, 0, 0)))
    rollback_name = f"{BACKUP_PATH}/update_{previous}_{time.strftime('%Y%m%d_%H%M')}.tgz"

    error = None
    rollback = tarfile.open(rollback_name, 'w:gz')
    try:
        count = install_archive(file_name, update['full'], rollback)
    except Exception as exc: # pylint: disable=broad-except
        error = exc
    saved = len(rollback.getmembers())
    rollback.close()
    if saved == 0:
        os.remove(rollback_name)

    if error is not None:
        logs.error(f"Unable to apply {update['file']} ({error})")
        if saved > 0:
            try:
                install_archive(rollback_name, False)
                logs.info(f"Version {previous} restored from {rollback_name}")
            except Exception as exc_restore: # pylint: disable=broad-except
                logs.error(f"Unable to restore {rollback_name} ({exc_restore})")
        return None

    logs.debug(f"{update['file']} applied ({count} files written, {saved} previous files saved)")

    if update['full']:
        os.remove(file_name)

    # VERSION comes from the archive : force it if it does not match the release,
    # else the same update would be proposed again and again
    if parse_version(get_version(logs)) != parse_version(update['version']):
        set_version(logs, f"{update['version']}_{time.strftime('%Y%m%d%H%M')}")

    return get_version(logs)

# Statistics of the games : the server of raspyhub (contract : README of the project
# « Raspy2DMD Serveur Télémétrie », section Statistiques RaspyDarts). The second address, in http,
# only after a failure of the network (the clock not set yet at boot : the certificate refused)
STATS_URLS = ('https://raspystats.raspyhub.fr/api/v1/raspydarts/plays',
              'http://raspystats.raspyhub.fr/api/v1/raspydarts/plays')
STATS_API_KEY = 'raspydarts_stats_2026'
STATS_TIMEOUT = 5
# The same identifier as Raspy2DMD (its recipe exactly) : a borne with both is one installation
MACHINE_ID_SALT = 'raspy2dmd_telemetry_salt_v1'
_machine_id = None


def machine_id():
    '''
    Identifier of the Raspberry : the serial of /proc/cpuinfo hashed (never sent as it is),
    as Raspy2DMD computes it. '' if unknown
    '''
    global _machine_id
    if _machine_id is None:
        _machine_id = ''
        try:
            with open('/proc/cpuinfo', encoding='utf-8') as file:
                found = re.search(r'Serial\s*:\s*([0-9a-fA-F]+)', file.read())
            if found:
                combined = f"{MACHINE_ID_SALT}:{found.group(1).strip()}:{MACHINE_ID_SALT}"
                _machine_id = hashlib.sha256(combined.encode()).hexdigest()[:16]
        except OSError:
            pass
    return _machine_id


def stats_options(options):
    '''
    The options of a game as the server takes them : a flat object of texts, numbers and
    booleans, 4 KB at most (the last ones left out beyond)
    '''
    flat = {}
    for key, value in (options or {}).items():
        if not isinstance(value, (str, int, float, bool)) or value is None:
            value = str(value)
        flat[str(key)] = value
        if len(json.dumps(flat)) > 4000:
            del flat[str(key)]
            break
    return flat


def send_infos(logs, game, nb_players, options, rpi_model, event, competition_mode, play_id, version,
               set_number=1, network=False):
    '''
    Statistics of a game (event : start, finished at the end of a set, canceled, interrupted),
    sent in the background : the game never waits for the network.
    (A test of the connection made when this module was imported held the start of the
    game up to 10 s at boot, the Wi-Fi not being connected yet : the desktop was seen
    after the intro)
    '''
    data = {'machine_id': machine_id(),
            'play_id': str(play_id),
            'event': event,
            'set': max(1, min(99, int(set_number))),
            'game': str(game)[:40],
            'game_type': 'network' if network else 'local',
            'nb_players': max(1, min(12, int(nb_players))),
            'play_mode': 'competition' if competition_mode else 'loisir',
            'options': stats_options(options),
            'version': str(version)[:40],
            'rpi_model': str(rpi_model)[:60],
            'sent_at': datetime.now().astimezone().isoformat(timespec='seconds')}
    Thread(target=post_infos, args=(logs, data), daemon=True).start()


def post_infos(logs, data):
    '''
    Send the statistics of a game (see send_infos). An answer of the server, whatever it is,
    ends the sending ; a failure of the network only goes on with the next address
    '''
    headers = {'Content-Type': 'application/json; charset=utf-8', 'X-API-Key': STATS_API_KEY}
    if not data['machine_id']:
        logs.debug("Statistics not sent : no serial number")
        return
    for url in STATS_URLS:
        try:
            res = requests.post(url, json=data, headers=headers, timeout=STATS_TIMEOUT)
        except requests.exceptions.RequestException as exception:
            logs.debug(f"Statistics : {url} unreachable ({exception})")
            continue
        if res.status_code == 200:
            logs.debug(f"Statistics sent ({data['event']}, {url})")
        else:
            logs.warning(f"Statistics refused by {url} : {res.status_code} {res.text[:200]}")
        return
    logs.debug("Statistics not sent : server unreachable")
